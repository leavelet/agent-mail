-- M6: public mode (invite codes, operator tokens, suspended orgs) and the
-- optional retention of message bodies.

-- Set while the operator has suspended the org: its tokens stop working and
-- mail to it is refused; its data is kept.
ALTER TABLE orgs ADD COLUMN suspended_at BIGINT;

-- Set when the retention period cleared the message's body (the header is
-- kept for the thread structure).
ALTER TABLE messages ADD COLUMN expired_at BIGINT;

-- One-time invite codes for registration (`POST /v1/register`), stored as
-- SHA-256 hashes.
CREATE TABLE invites (
    id          BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hash        TEXT    NOT NULL UNIQUE,
    note        TEXT,
    created_at  BIGINT  NOT NULL,
    expires_at  BIGINT,
    used_at     BIGINT,
    -- The org created with it (by name: kept when the org is deleted).
    used_by     TEXT,
    revoked_at  BIGINT
);

-- Operator tokens belong to no org; they are issued on the database only
-- (`amail admin operator-token`). Browser sessions of operators.
CREATE TABLE operator_tokens (
    id          BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hash        TEXT    NOT NULL UNIQUE,
    label       TEXT,
    created_at  BIGINT  NOT NULL,
    revoked_at  BIGINT
);
CREATE TABLE operator_sessions (
    hash        TEXT    PRIMARY KEY,
    token_id    BIGINT  NOT NULL REFERENCES operator_tokens(id),
    created_at  BIGINT  NOT NULL,
    expires_at  BIGINT  NOT NULL
);

-- Deleting an org: find its tokens, and the replies to its messages (the
-- foreign key check on parent_id needs the index on Postgres).
CREATE INDEX tokens_org ON tokens(org_id);
CREATE INDEX messages_parent ON messages(parent_id) WHERE parent_id IS NOT NULL;
