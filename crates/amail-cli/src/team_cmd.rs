//! `amail up`, `down`, `ps`, `attach`, `sleep`, `wake`: thin clients of
//! the node socket (which starts and supervises sessions), plus the server
//! calls that align seats and lists with the team file.

use crate::Out;
use crate::client::{Client, enc};
use amail_node::mux::AttachPlan;
use amail_node::team::{self, Team};
use amail_node::wire::{GitAccess, PsRow, Request, SeatPlacement};
use amail_proto::{self as p, PostPolicy, SeatKind, TokenScope};
use anyhow::{Context, Result, bail};
use reqwest::Method;
use serde_json::{Value, json};
use std::collections::{BTreeMap, BTreeSet};
use std::path::PathBuf;
use std::time::Duration;

const LIST_DESCRIPTION: &str = "generated by amail up";

fn node(req: &Request, timeout: Duration) -> Result<Value> {
    let sock = amail_node::paths::socket();
    if !sock.exists() {
        bail!(
            "the amail node is not running (no socket at {}); start it first with `amail node`",
            sock.display()
        );
    }
    amail_node::request(&sock, req, timeout)
}

/// The node's local policy as `ps`, `up` and `doctor` show it, from a
/// `Ps`, `Up` or `Status` answer.
pub fn policy_line(v: &Value) -> Option<String> {
    policy_text(v).map(|t| format!("local policy: {t}"))
}

/// [`policy_line`] without its `local policy: ` label.
pub fn policy_text(v: &Value) -> Option<String> {
    let p = v["local_policy"].as_str()?;
    let source = v["local_policy_source"]
        .as_str()
        .map(|s| format!(" ({s})"))
        .unwrap_or_default();
    let what = match p {
        "open" => {
            "agent sessions on this host may manage seats and obtain any seat's credentials; \
             the node reports such requests to you by system mail"
        }
        "restricted" => {
            "agent sessions on this host get only their own seat's credentials and cannot \
             manage seats (best effort)"
        }
        _ => "",
    };
    Some(format!("{p}{source}: {what}"))
}

/// Whether the node on this host works for the server `c` talks to (the
/// same URL), so that a seat missing on that server may be forgotten.
fn node_serves(c: &Client) -> bool {
    node(&Request::Status, Duration::from_secs(10))
        .ok()
        .and_then(|v| {
            v["server"]
                .as_str()
                .map(|u| u.trim_end_matches('/') == c.base())
        })
        .unwrap_or(false)
}

/// After seat `seat` was deleted on the server: if the node on this host
/// supervises it, stop it and remove it from the node's seats. Returns
/// whether that was done. No node: nothing to do.
pub fn forget_deleted(c: &Client, seat: &str) -> Result<bool> {
    if !amail_node::paths::socket().exists() {
        return Ok(false);
    }
    if !ps_rows()?.iter().any(|r| r.seat == seat) || !node_serves(c) {
        return Ok(false);
    }
    node(
        &Request::Forget {
            seats: vec![seat.to_string()],
        },
        Duration::from_secs(60),
    )?;
    Ok(true)
}

fn ps_rows() -> Result<Vec<PsRow>> {
    let v = node(&Request::Ps, Duration::from_secs(10))?;
    Ok(serde_json::from_value(v["seats"].clone())?)
}

/// Seats of supervised groups or seats named in `only` (all when empty).
fn resolve(rows: &[PsRow], only: &[String]) -> Result<Vec<String>> {
    if only.is_empty() {
        return Ok(Vec::new());
    }
    let mut out = Vec::new();
    for o in only {
        let hits: Vec<String> = rows
            .iter()
            .filter(|r| &r.seat == o || r.group.as_deref() == Some(o.as_str()))
            .map(|r| r.seat.clone())
            .collect();
        if hits.is_empty() {
            bail!("no supervised group or seat {o:?} (see amail ps)");
        }
        out.extend(hits);
    }
    out.sort();
    out.dedup();
    Ok(out)
}

pub struct UpOpts {
    pub file: PathBuf,
    pub only: Vec<String>,
    pub no_start: bool,
    pub prune: bool,
}

/// The fields of a seat that `up` manages.
fn desired_seat(t: &Team, s: &team::SeatPlan, main: &str) -> p::NewSeat {
    let role = amail_node::template::role_text(t, &s.name, main);
    p::NewSeat {
        name: s.name.clone(),
        parent: s.parent.clone(),
        display_name: s.display_name.clone(),
        role: Some(role).filter(|r| !r.is_empty()),
        harness: Some(s.harness.clone()),
        model: s.model.clone(),
        permission_mode: s.permission_mode,
        group: s.group.clone(),
    }
}

/// The patch that turns `cur` into `want`, and the names of changed fields.
fn seat_patch(
    cur: &p::Seat,
    want: &p::NewSeat,
) -> (serde_json::Map<String, Value>, Vec<&'static str>) {
    let mut patch = serde_json::Map::new();
    let mut changed = Vec::new();
    let mut field = |name: &'static str, a: Value, b: Value| {
        if a != b {
            patch.insert(name.to_string(), b);
            changed.push(name);
        }
    };
    field("parent", json!(cur.parent), json!(want.parent));
    field(
        "display_name",
        json!(cur.display_name),
        json!(want.display_name),
    );
    field("role", json!(cur.role), json!(want.role));
    field("harness", json!(cur.harness), json!(want.harness));
    field("model", json!(cur.model), json!(want.model));
    field(
        "permission_mode",
        json!(cur.permission_mode),
        json!(want.permission_mode),
    );
    field("group", json!(cur.group), json!(want.group));
    (patch, changed)
}

pub async fn up(c: &Client, out: &Out, o: &UpOpts) -> Result<()> {
    // 1. Everything that can fail without changing anything.
    let t = team::load(&o.file).map_err(|e| anyhow::anyhow!("{e}"))?;
    let selected = t.select(&o.only).map_err(|e| anyhow::anyhow!("{e}"))?;
    let rows = ps_rows()?;
    let me: p::WhoAmI = c.get("/whoami").await?;
    if me.scope != TokenScope::User {
        bail!(
            "amail up needs a user token (AMAIL_TOKEN), not a {} token",
            me.scope
        );
    }
    let main = match (&t.repo, t.uses_worktrees()) {
        (Some(repo), true) => {
            amail_node::worktree::check_repo(repo)?;
            amail_node::worktree::main_branch(repo)?
        }
        _ => "main".to_string(),
    };
    let mut server_seats: Vec<p::Seat> = c.get("/seats").await?;
    // The list cuts long roles; compare with the whole one.
    for s in server_seats.iter_mut().filter(|s| s.role_truncated) {
        *s = c.get(&format!("/seats/{}", s.name)).await?;
    }
    let by_name: BTreeMap<&str, &p::Seat> =
        server_seats.iter().map(|s| (s.name.as_str(), s)).collect();
    for s in &t.seats {
        if by_name
            .get(s.name.as_str())
            .is_some_and(|x| x.kind == SeatKind::User)
        {
            bail!("seat {:?} in the team file is the org's user seat", s.name);
        }
    }
    let server_lists: Vec<p::List> = c.get("/lists").await?;
    for (name, _, _) in t.lists() {
        if by_name.contains_key(name.as_str()) {
            bail!("the generated list {name:?} would clash with an existing seat of that name");
        }
    }
    let mut report: Vec<String> = Vec::new();

    // 2. Working directories.
    if t.uses_worktrees() {
        let repo = t.repo.clone().context("repo")?;
        let specs: Vec<amail_node::worktree::WorktreeSpec> = t
            .seats
            .iter()
            .map(|s| amail_node::worktree::WorktreeSpec {
                path: t.workdir(&s.name),
                branch: t.branch(&s.name),
                integration: t
                    .needs_integration_branch(&s.name)
                    .then(|| t.integration_branch(&s.name, &main)),
            })
            .collect();
        for line in amail_node::worktree::prepare(&repo, &main, &specs)? {
            report.push(format!("git: {line}"));
        }
    } else {
        for s in &t.seats {
            let d = t.workdir(&s.name);
            if !d.exists() {
                std::fs::create_dir_all(&d).with_context(|| format!("creating {}", d.display()))?;
                report.push(format!("created directory {}", d.display()));
            }
        }
    }

    // 3. Seats on the server (parents first).
    let live: BTreeMap<&str, &PsRow> = rows
        .iter()
        .filter(|r| !matches!(r.state.as_str(), "offline" | "dormant" | "failed"))
        .map(|r| (r.seat.as_str(), r))
        .collect();
    let mut restart_needed = Vec::new();
    let mut created = Vec::new();
    for s in &t.seats {
        let want = desired_seat(&t, s, &main);
        match by_name.get(s.name.as_str()) {
            None => {
                c.raw(Method::POST, "/seats", Some(&serde_json::to_value(&want)?))
                    .await
                    .with_context(|| format!("creating seat {}", s.name))?;
                created.push(s.name.clone());
            }
            Some(cur) => {
                let (patch, changed) = seat_patch(cur, &want);
                if changed.is_empty() {
                    continue;
                }
                c.raw(
                    Method::PATCH,
                    &format!("/seats/{}", enc(&s.name)),
                    Some(&Value::Object(patch)),
                )
                .await
                .with_context(|| format!("updating seat {}", s.name))?;
                report.push(format!("updated seat {}: {}", s.name, changed.join(", ")));
                if live.contains_key(s.name.as_str()) && changed.iter().any(|f| *f != "group") {
                    restart_needed.push(s.name.clone());
                }
            }
        }
    }
    if !created.is_empty() {
        report.push(format!("created seats: {}", created.join(", ")));
    }
    // Seats that left the file.
    let in_file: BTreeSet<&str> = t.seats.iter().map(|s| s.name.as_str()).collect();
    // Supervised seats that were deleted on the server (e.g. with `amail
    // seat rm` on another host): the node stops them and drops them.
    let gone: Vec<String> = rows
        .iter()
        .filter(|r| !in_file.contains(r.seat.as_str()) && !by_name.contains_key(r.seat.as_str()))
        .map(|r| r.seat.clone())
        .collect();
    if !gone.is_empty() && node_serves(c) {
        node(
            &Request::Forget {
                seats: gone.clone(),
            },
            Duration::from_secs(60),
        )?;
        report.push(format!(
            "stopped and dropped seats that no longer exist on the server: {}",
            gone.join(", ")
        ));
    }
    let mut removed: Vec<String> = rows
        .iter()
        .filter(|r| !in_file.contains(r.seat.as_str()) && !gone.contains(&r.seat))
        .map(|r| r.seat.clone())
        .collect();
    for s in &server_seats {
        if s.kind == SeatKind::Agent
            && s.group.is_some()
            && !in_file.contains(s.name.as_str())
            && !removed.contains(&s.name)
        {
            removed.push(s.name.clone());
        }
    }
    if !removed.is_empty() && o.only.is_empty() {
        if o.prune {
            let supervised: Vec<String> = removed
                .iter()
                .filter(|n| rows.iter().any(|r| &r.seat == *n))
                .cloned()
                .collect();
            if !supervised.is_empty() {
                node(
                    &Request::Forget { seats: supervised },
                    Duration::from_secs(60),
                )?;
            }
            for n in &removed {
                if by_name.contains_key(n.as_str()) {
                    c.raw(Method::DELETE, &format!("/seats/{}", enc(n)), None)
                        .await
                        .with_context(|| format!("deleting seat {n}"))?;
                }
            }
            report.push(format!("pruned seats: {}", removed.join(", ")));
        } else {
            report.push(format!(
                "not in the team file (kept; use --prune to delete): {}",
                removed.join(", ")
            ));
        }
    }

    // 4. Generated lists.
    let lists_by_name: BTreeMap<&str, &p::List> =
        server_lists.iter().map(|l| (l.name.as_str(), l)).collect();
    let wanted = t.lists();
    for (name, members, user_only) in &wanted {
        let policy = if *user_only {
            PostPolicy::UserOnly
        } else {
            PostPolicy::Anyone
        };
        let existing = lists_by_name.get(name.as_str());
        let mut fresh = false;
        match existing {
            Some(l) if !l.managed => {
                report.push(format!(
                    "list {name} exists and was not made by amail up: left unchanged"
                ));
                continue;
            }
            Some(l) if l.post_policy != policy => {
                c.raw(Method::DELETE, &format!("/lists/{}", enc(name)), None)
                    .await?;
                fresh = true;
            }
            Some(_) => {}
            None => fresh = true,
        }
        let have: BTreeSet<String> = if fresh {
            c.raw(
                Method::POST,
                "/lists",
                Some(
                    &json!({"name": name, "post_policy": policy, "managed": true,
                             "description": LIST_DESCRIPTION}),
                ),
            )
            .await
            .with_context(|| format!("creating list {name}"))?;
            BTreeSet::new()
        } else {
            let l: p::List = c.get(&format!("/lists/{}", enc(name))).await?;
            l.members
                .unwrap_or_default()
                .into_iter()
                .map(|m| m.address)
                .collect()
        };
        let want: BTreeSet<String> = members.iter().cloned().collect();
        let add: Vec<&String> = want.difference(&have).collect();
        let drop: Vec<&String> = have.difference(&want).collect();
        for m in &add {
            c.raw(
                Method::PUT,
                &format!("/lists/{}/members/{}", enc(name), enc(m)),
                Some(&json!({"mode": "immediate"})),
            )
            .await
            .with_context(|| format!("adding {m} to list {name}"))?;
        }
        for m in &drop {
            c.raw(
                Method::DELETE,
                &format!("/lists/{}/members/{}", enc(name), enc(m)),
                None,
            )
            .await?;
        }
        if fresh {
            report.push(format!("list {name}: {} members", want.len()));
        } else if !add.is_empty() || !drop.is_empty() {
            report.push(format!(
                "list {name}: +{} -{} members",
                add.len(),
                drop.len()
            ));
        }
    }
    let wanted_names: BTreeSet<&str> = wanted.iter().map(|(n, _, _)| n.as_str()).collect();
    let stale: Vec<&str> = server_lists
        .iter()
        .filter(|l| l.managed && !wanted_names.contains(l.name.as_str()))
        .map(|l| l.name.as_str())
        .collect();
    if !stale.is_empty() {
        if o.prune {
            for l in &stale {
                c.raw(Method::DELETE, &format!("/lists/{}", enc(l)), None)
                    .await?;
            }
            report.push(format!("pruned lists: {}", stale.join(", ")));
        } else {
            report.push(format!(
                "generated lists no longer in the team (use --prune): {}",
                stale.join(", ")
            ));
        }
    }

    // 5. Sessions, through the node.
    let placements: Vec<SeatPlacement> = t
        .placements()
        .into_iter()
        .map(|(s, g, tab)| {
            let plan = t.seat(&s).expect("placed seats exist");
            SeatPlacement {
                seat: s.clone(),
                group: plan.group.clone(),
                harness: plan.harness.clone(),
                cwd: t.workdir(&s).to_string_lossy().into_owned(),
                mux_session: format!("amail-{}-{g}", me.org),
                tab,
                paste_fallback: plan.paste_fallback,
                permission_mode: plan.permission_mode,
                git_access: Some(t.git_access(&s)),
                dsh_jail: plan.dsh_jail,
            }
        })
        .collect();
    for p in &placements {
        if p.harness == "dsh"
            && p.dsh_jail == Some(false)
            && p.permission_mode == Some(p::PermissionMode::Unattended)
        {
            report.push(format!(
                "seat {}: dsh_jail off: this unattended dsh seat runs without the jail, so \
                 its agent can read every file your OS user can read (saved logins and keys \
                 included)",
                p.seat
            ));
        }
        if p.harness == "codex" && p.git_access == Some(GitAccess::Full) {
            let why = if t.seat(&p.seat).is_some_and(|s| s.git_access.is_some()) {
                "set in the team file"
            } else {
                "the staged-merge root merges in the main checkout"
            };
            report.push(format!(
                "seat {}: git_access full ({why}): its Codex sessions can write the whole \
                 git directory and the main checkout, including git hooks and config, so \
                 they can make git run commands outside their sandbox",
                p.seat
            ));
        }
    }
    let v = node(
        &Request::Up {
            seats: placements,
            settings: t.settings.clone(),
            start: !o.no_start,
            only: (!o.only.is_empty()).then(|| selected.clone()),
        },
        Duration::from_secs(30),
    )?;
    for c in v["settings_changed"].as_array().into_iter().flatten() {
        if let Some(c) = c.as_str() {
            report.push(format!("settings changed (in effect now): {c}"));
        }
    }
    if let Some(l) = policy_line(&v) {
        report.push(l);
    }
    let mut by_action: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for s in v["seats"].as_array().into_iter().flatten() {
        by_action
            .entry(s["action"].as_str().unwrap_or("?").to_string())
            .or_default()
            .push(s["seat"].as_str().unwrap_or("?").to_string());
    }
    for (action, seats) in &by_action {
        report.push(format!("{action}: {}", seats.join(", ")));
    }
    if !restart_needed.is_empty() {
        report.push(format!(
            "changed while running (takes effect after a restart, e.g. amail sleep + amail wake): {}",
            restart_needed.join(", ")
        ));
    }
    let all = json!({
        "org": me.org,
        "seats": v["seats"],
        "report": report,
        "restart_needed": restart_needed,
    });
    out.show(&all, || Ok(report.join("\n")))
}

pub fn down(only: &[String], out: &Out) -> Result<()> {
    let rows = ps_rows()?;
    let seats = resolve(&rows, only)?;
    let v = node(&Request::Down { seats }, Duration::from_secs(120))?;
    out.show(&v, || {
        let mut lines = Vec::new();
        let stopped: Vec<&str> = v["stopped"]
            .as_array()
            .into_iter()
            .flatten()
            .filter_map(Value::as_str)
            .collect();
        lines.push(format!("stopped: {}", stopped.join(", ")));
        let left: Vec<&str> = v["still_running"]
            .as_array()
            .into_iter()
            .flatten()
            .filter_map(Value::as_str)
            .collect();
        if !left.is_empty() {
            lines.push(format!("still running: {}", left.join(", ")));
        }
        let closed: Vec<&str> = v["closed_sessions"]
            .as_array()
            .into_iter()
            .flatten()
            .filter_map(Value::as_str)
            .collect();
        if !closed.is_empty() {
            lines.push(format!("closed zellij sessions: {}", closed.join(", ")));
        }
        Ok(lines.join("\n"))
    })
}

fn ago(ts: &str) -> String {
    let Ok(t) = ts.parse::<jiff::Timestamp>() else {
        return ts.to_string();
    };
    let secs = (jiff::Timestamp::now().as_second() - t.as_second()).max(0);
    match secs {
        0..60 => format!("{secs}s ago"),
        60..3600 => format!("{}m ago", secs / 60),
        3600..86_400 => format!("{}h ago", secs / 3600),
        _ => format!("{}d ago", secs / 86_400),
    }
}

pub fn ps(out: &Out) -> Result<()> {
    let v = node(&Request::Ps, Duration::from_secs(10))?;
    let rows: Vec<PsRow> = serde_json::from_value(v["seats"].clone())?;
    out.show(&v, || {
        if rows.is_empty() {
            let mut lines = vec!["no supervised seats (start a team with amail up)".to_string()];
            lines.extend(policy_line(&v));
            return Ok(lines.join("\n"));
        }
        let mut table = vec![[
            "SEAT".to_string(),
            "STATE".into(),
            "PANE".into(),
            "PENDING".into(),
            "ACTIVE".into(),
            "ATTENTION".into(),
        ]];
        for r in &rows {
            table.push([
                r.seat.clone(),
                r.state.clone(),
                match r.pane {
                    Some(p) => format!("{}:{p}", r.mux_session),
                    None => r.mux_session.clone(),
                },
                r.pending.to_string(),
                r.last_activity
                    .as_deref()
                    .map(ago)
                    .unwrap_or_else(|| "-".into()),
                r.attention.clone().unwrap_or_else(|| "-".into()),
            ]);
        }
        let widths: Vec<usize> = (0..6)
            .map(|i| {
                table
                    .iter()
                    .map(|r| r[i].chars().count())
                    .max()
                    .unwrap_or(0)
            })
            .collect();
        let mut lines: Vec<String> = table
            .iter()
            .map(|r| {
                r.iter()
                    .enumerate()
                    .map(|(i, c)| format!("{c:<w$}", w = widths[i]))
                    .collect::<Vec<_>>()
                    .join("  ")
                    .trim_end()
                    .to_string()
            })
            .collect();
        for r in &rows {
            if let Some(h) = &r.hint {
                lines.push(format!("{}: {h}", r.seat));
            }
        }
        if v["connected"].as_bool() == Some(false) {
            lines.push("(the node is not connected to the server)".into());
        }
        lines.extend(policy_line(&v));
        Ok(lines.join("\n"))
    })
}

pub fn attach(target: &str) -> Result<()> {
    use std::os::unix::process::CommandExt;
    let v = node(
        &Request::Locate {
            target: target.to_string(),
        },
        Duration::from_secs(10),
    )?;
    let plan: AttachPlan = if v["plan"].is_object() {
        serde_json::from_value(v["plan"].clone())?
    } else {
        // A node from before attach plans: run all commands but the last,
        // then exec the last.
        let mut cmds: Vec<Vec<String>> = serde_json::from_value(v["commands"].clone())?;
        let attach = cmds.pop().context("nothing to attach to")?;
        AttachPlan {
            session: v["session"].as_str().unwrap_or_default().to_string(),
            tab: None,
            pane: None,
            busy_check: None,
            focus: cmds,
            attach,
        }
    };
    if plan.attach.is_empty() || plan.focus.iter().any(Vec::is_empty) {
        bail!("the node sent an empty command");
    }
    // Quiet: these print tab ids and errors that mean nothing here.
    let quiet = |c: &[String]| {
        std::process::Command::new(&c[0])
            .args(&c[1..])
            .stdin(std::process::Stdio::null())
            .stdout(std::process::Stdio::null())
            .stderr(std::process::Stdio::null())
            .status()
            .is_ok_and(|s| s.success())
    };
    let busy = plan
        .busy_check
        .as_deref()
        .is_some_and(|c| !c.is_empty() && quiet(c));
    if busy {
        if let Some(tab) = &plan.tab {
            eprintln!(
                "Another terminal attached to session {} is in use, so amail cannot choose the \
                 tab this one starts on. Go to tab {tab:?} yourself (in zellij: Ctrl t, then \
                 the arrow keys, then Enter).",
                plan.session
            );
            if std::io::IsTerminal::is_terminal(&std::io::stderr()) {
                std::thread::sleep(Duration::from_secs(3));
            }
        }
    } else {
        for c in &plan.focus {
            quiet(c);
        }
    }
    let last = &plan.attach;
    let err = std::process::Command::new(&last[0]).args(&last[1..]).exec();
    Err(anyhow::anyhow!("running {}: {err}", last[0]))
}

pub fn sleep(seat: &str, out: &Out) -> Result<()> {
    let v = node(
        &Request::Sleep {
            seat: seat.to_string(),
        },
        Duration::from_secs(60),
    )?;
    out.show(&v, || {
        Ok(if v["asleep"].as_bool() == Some(true) {
            format!("{seat} is asleep")
        } else {
            format!("{seat} is still stopping")
        })
    })
}

pub fn wake(seat: &str, out: &Out) -> Result<()> {
    let v = node(
        &Request::Wake {
            seat: seat.to_string(),
        },
        Duration::from_secs(10),
    )?;
    out.show(&v, || {
        Ok(format!("{seat}: {}", v["action"].as_str().unwrap_or("?")))
    })
}
