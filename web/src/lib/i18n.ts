export const dictionaries: Record<Lang, Record<Key, string>> = { en, zh };

export function translate(lang: Lang, key: Key, params?: Record<string, string | number>): string {
  let s = dictionaries[lang][key] ?? dictionaries.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}

/** The interface language for a browser language tag. */
export function langFor(tag: string | undefined | null): Lang {
  return tag && tag.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function isKey(k: string): k is Key {
  return Object.prototype.hasOwnProperty.call(en, k);
}
